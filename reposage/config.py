from __future__ import annotations

import ast
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

CONFIG_NAME = ".reposage.toml"

DEFAULT_PLUGINS = [
    "overview",
    "structure",
    "endpoints",
    "dependencies",
    "todos",
    "security",
    "conventions",
]


@dataclass
class Config:
    name: str = ""
    out_dir: str = "reposage-out"
    max_depth: int = 24
    max_files: int = 3000
    max_file_kb: int = 500
    read_budget_mb: int = 100
    plugins: list = field(default_factory=lambda: list(DEFAULT_PLUGINS))
    extra_ignore: list = field(default_factory=list)
    max_todos: int = 100
    max_endpoints: int = 250
    max_findings: int = 100

    def with_overrides(self, **kwargs: Any) -> "Config":
        data = {k: getattr(self, k) for k in self.__dataclass_fields__}
        data.update({k: v for k, v in kwargs.items() if v is not None})
        return Config(**data)


def _scalar(value: str) -> Any:
    value = value.strip()
    if len(value) >= 2 and value[0] in "\"'" and value[-1] == value[0]:
        return value[1:-1]
    try:
        return ast.literal_eval(value)
    except (ValueError, SyntaxError):
        return value


def _parse_toml(text: str) -> dict:
    root: dict = {}
    current: dict = root
    pending_list: Optional[list] = None
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if pending_list is not None:
            if line.endswith("]"):
                item = line[:-1].strip().rstrip(",")
                if item:
                    pending_list.append(_scalar(item))
                pending_list = None
            else:
                item = line.rstrip(",").strip()
                if item:
                    pending_list.append(_scalar(item))
            continue
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            keys = [k.strip().strip("\"'") for k in line[1:-1].split(".")]
            current = root
            for key in keys:
                current = current.setdefault(key, {})
            continue
        if "=" in line:
            key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip()
            if value == "[":
                current[key] = []
                pending_list = current[key]
            else:
                current[key] = _scalar(value)
    return root


def load_config(root: Path) -> Config:
    config = Config()
    path = root / CONFIG_NAME
    if not path.is_file():
        return config
    try:
        data = _parse_toml(path.read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return config
    general = data.get("general", {})
    if isinstance(general, dict):
        for key in ("name", "out_dir", "max_depth", "max_files", "max_file_kb", "read_budget_mb"):
            if key in general:
                setattr(config, key, general[key])
    plugins = data.get("plugins", {})
    if isinstance(plugins, dict) and isinstance(plugins.get("enabled"), list):
        config.plugins = [p for p in plugins["enabled"] if isinstance(p, str)]
    ignore = data.get("ignore", {})
    if isinstance(ignore, dict) and isinstance(ignore.get("extra"), list):
        config.extra_ignore = [p for p in ignore["extra"] if isinstance(p, str)]
    return config


CONFIG_TEMPLATE = """\
# RepoSage configuration - generated by `reposage init`
# Full reference: https://github.com/Reda3D/reposage#configuration

[general]
name = ""               # display name (defaults to repo or directory name)
out_dir = "reposage-out"  # where the context pack is written
max_depth = 24          # max directory depth to scan
max_files = 3000        # max files to scan
max_file_kb = 500       # files larger than this (KB) are skipped
read_budget_mb = 100    # total content budget for reading files (MB)

[plugins]
enabled = ["overview", "structure", "endpoints", "dependencies", "todos", "security", "conventions"]

[ignore]
extra = []              # additional ignore patterns (gitignore syntax)
"""


def write_default_config(root: Path, force: bool = False) -> tuple[bool, Path]:
    path = root / CONFIG_NAME
    if path.exists() and not force:
        return False, path
    path.write_text(CONFIG_TEMPLATE, encoding="utf-8")
    return True, path
